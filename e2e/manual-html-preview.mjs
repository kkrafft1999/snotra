async function openInTree(...names) {
  for (const name of names) {
    await poll(() => page.evaluate((labelText) => {
      const row = [...document.querySelectorAll('#tree-container .tree-item')]
        .find((el) => el.querySelector('.label')?.textContent === labelText);
      row?.click();
      return Boolean(row);
    }, name), { what: name });
  }
}

/** The pane, with the page laid in where the view sits. */
async function shoot(state) {
  for (const theme of ['light', 'dark']) {
    await page.evaluate((th) => {
      if (th === 'dark') document.documentElement.dataset.theme = 'dark';
      else delete document.documentElement.dataset.theme;
    }, theme);
    await new Promise((resolve) => setTimeout(resolve, 400));
    const pane = await page.locator('#content').screenshot();
    const overlay = await app.evaluate(async ({ BrowserWindow }) => {
      const win = BrowserWindow.getAllWindows()[0];
      const view = win.contentView.children.find((v) => v.webContents?.getURL().startsWith('snotra-html:'));
      if (!view || !view.getVisible()) return null;
      const image = await view.webContents.capturePage();
      return { data: image.toDataURL(), bounds: view.getBounds(), zoom: win.webContents.getZoomFactor() };
    });
    const composed = await page.evaluate(async ({ paneData, overlay }) => {
      const load = (src) => new Promise((resolve) => {
        const img = new Image();
        img.onload = () => resolve(img);
        img.src = src;
      });
      const base = await load(paneData);
      const rect = document.getElementById('content').getBoundingClientRect();
      const scale = base.width / rect.width;
      const canvas = document.createElement('canvas');
      canvas.width = base.width;
      canvas.height = base.height;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(base, 0, 0);
      if (overlay) {
        const img = await load(overlay.data);
        const { x, y, width, height } = overlay.bounds;
        const z = overlay.zoom || 1;
        ctx.drawImage(img, (x / z - rect.left) * scale, (y / z - rect.top) * scale, (width / z) * scale, (height / z) * scale);
      }
      return canvas.toDataURL('image/png');
    }, { paneData: `data:image/png;base64,${pane.toString('base64')}`, overlay });
    await writeFile(path.join(SHOTS, `html-${label}-${state}-${theme}.png`), Buffer.from(composed.split(',')[1], 'base64'));
  }
  console.log(`shot ${state}`);
}

